"""Generate Lean declarations from the stored 50-row transcription.

Requires SymPy 1.14.0 only for regeneration. Lean independently checks the
generated identities; the generator and SymPy are not trusted proof oracles.
Run from this package: python scripts/generate-region-algebra.py.
"""
from pathlib import Path
import json
import sympy as S

ROOT = Path(__file__).resolve().parent.parent
t, d, U, V, P, N, E, F, G = S.symbols("t d U V P N E F G")
VARIABLES = {str(x): x for x in (t, d, U, V, P, N, E, F, G)}


def lean(expr):
    """Print a fully parenthesized field expression with integer powers."""
    expr = S.sympify(expr)
    if expr.is_Integer:
        return str(expr) if expr >= 0 else f"({expr})"
    if expr.is_Rational:
        return f"({expr.p} / {expr.q})"
    if expr.is_Symbol:
        return str(expr)
    if expr.is_Add:
        return "(" + " + ".join(lean(a) for a in expr.args) + ")"
    if expr.is_Mul:
        return "(" + " * ".join(lean(a) for a in expr.args) + ")"
    if expr.is_Pow and expr.exp.is_Integer:
        n = int(expr.exp)
        if n < 0:
            return f"(({lean(expr.base)} ^ {-n})⁻¹)"
        return f"({lean(expr.base)} ^ {n})"
    raise ValueError(f"Unsupported expression: {expr}")


def vec(exprs):
    return "![" + ",\n    ".join(lean(x) for x in exprs) + "]"

def cases(exprs):
    return "fun i => match i.val with\n" + "\n".join(
        f"    | {i} => {lean(x)}" for i,x in enumerate(exprs)) + "\n    | _ => 0"


def main():
    rows = json.loads((ROOT / "data/region-expressions.json").read_text(encoding="utf-8"))
    exprs = [S.sympify(row["expression"], locals=VARIABLES) for row in rows]
    common = d**2 * P * N * E * F * G
    nums = [S.factor(S.cancel(common * row)) for row in exprs]
    assert all(S.denom(x) == 1 for x in nums)
    substitute = {P: 1-d*V*t, N: 1-V*t/d, E: 1-V**2*t**2,
                  F: 1-U*t**2, G: 1-U*t**4}
    polynomial_sum = S.cancel(sum(nums).subs(substitute))
    H = S.cancel(polynomial_sum / ((1-V**2*t**2)*(1-U*t**2)*(1-U*t**4)))
    H = S.Poly(H, U, V)
    h_expr = sum(S.factor(c) * U**i * V**j for (i,j),c in H.terms())
    raw_sum = S.factor(sum(nums))
    params = "t d U V P N E F G"
    small_declarations = []
    for i,(term,num) in enumerate(zip(exprs,nums)):
        small_declarations += [
            f"def regionTerm{i} ({params} : K) : K := {lean(term)}",
            f"def regionNumerator{i} ({params} : K) : K := {lean(num)}",
            f"theorem regionCleared{i} ({params} : K)",
            "    (hd : d ≠ 0) (hP : P ≠ 0) (hN : N ≠ 0) (hE : E ≠ 0)",
            "    (hF : F ≠ 0) (hG : G ≠ 0) :",
            f"    (d ^ 2 * P * N * E * F * G) * regionTerm{i} {params} =",
            f"      regionNumerator{i} {params} := by",
            f"  unfold regionTerm{i} regionNumerator{i}",
            "  field_simp",
            "  <;> ring",
            "",
        ]
    out = [
        "import Mathlib.Algebra.BigOperators.Fin",
        "import Mathlib.Data.Fin.VecNotation",
        "import Mathlib.Tactic.FinCases",
        "import Mathlib.Tactic.FieldSimp",
        "import Mathlib.Tactic.Ring",
        "",
        "/-!",
        "# The exact fifty-region rational identity",
        "",
        "Generated by scripts/generate-region-algebra.py from data/region-expressions.json.",
        "Each entry is a transcription of a printed rational region expression after",
        "putting t = q^(-1/2). This file proves their finite algebraic sum.",
        "It does not claim that the corresponding infinite valuation sums equal these",
        "expressions, or that a period integral equals their sum.",
        "-/",
        "",
        "namespace FourierJacobi",
        "namespace Algebra",
        "variable {K : Type*} [Field K]",
        "set_option maxHeartbeats 4000000",
        "set_option maxRecDepth 4096",
        "-- The generated rows intentionally share a uniform parameter/proof interface.",
        "set_option linter.unusedVariables false",
        "set_option linter.unusedTactic false",
        "set_option linter.unreachableTactic false",
        "set_option linter.unnecessarySeqFocus false",
        "",
        *small_declarations,
        "/-- Auxiliary denominator variables keep each cancellation proof small. -/",
        "def rawRegionTerms (t d U V P N E F G : K) : Fin 50 → K :=",
        "  ![" + ", ".join(f"regionTerm{i} {params}" for i in range(50)) + "]",
        "",
        "def rawRegionNumerators (t d U V P N E F G : K) : Fin 50 → K :=",
        "  ![" + ", ".join(f"regionNumerator{i} {params}" for i in range(50)) + "]",
        "",
        "def kernelNumerator (t d U V : K) : K :=",
        "  " + lean(h_expr),
        "",
        "set_option maxHeartbeats 4000000 in",
        "/-- Denominators are explicit hypotheses, never silently cancelled at zero. -/",
        "theorem region_term_cleared (t d U V P N E F G : K)",
        "    (hd : d ≠ 0) (hP : P ≠ 0) (hN : N ≠ 0) (hE : E ≠ 0)",
        "    (hF : F ≠ 0) (hG : G ≠ 0) (i : Fin 50) :",
        "    (d ^ 2 * P * N * E * F * G) * rawRegionTerms t d U V P N E F G i =",
        "      rawRegionNumerators t d U V P N E F G i := by",
        "  fin_cases i",
        *[f"  · exact regionCleared{i} {params} hd hP hN hE hF hG" for i in range(50)],
        "",
        "def regionTerms (t d U V : K) : Fin 50 → K :=",
        "  rawRegionTerms t d U V (1 - d * V * t) (1 - V * t / d)",
        "    (1 - V ^ 2 * t ^ 2) (1 - U * t ^ 2) (1 - U * t ^ 4)",
        "",
        "def regionKernel (t d U V : K) : K :=",
        "  kernelNumerator t d U V / (d ^ 2 * (1 - d * V * t) * (1 - V * t / d))",
        "",
        "def rawNumeratorSum (t d U V P N E F G : K) : K := "+lean(raw_sum),
        "",
        "set_option maxHeartbeats 8000000 in",
        "theorem raw_numerators_sum (t d U V P N E F G : K) :",
        "    (∑ i : Fin 50, rawRegionNumerators t d U V P N E F G i) =",
        "      rawNumeratorSum t d U V P N E F G := by",
        "  simp only [rawRegionNumerators, Fin.sum_univ_succ, Fin.sum_univ_zero,",
        "    Matrix.cons_val_zero, Matrix.cons_val_succ]",
        "  unfold "+ " ".join(f"regionNumerator{i}" for i in range(50)) + " rawNumeratorSum",
        "  ring",
        "",
        "set_option maxHeartbeats 8000000 in",
        "theorem region_numerators_sum (t d U V : K) (hd : d ≠ 0) :",
        "    (∑ i : Fin 50, rawRegionNumerators t d U V",
        "      (1 - d * V * t) (1 - V * t / d)",
        "      (1 - V ^ 2 * t ^ 2) (1 - U * t ^ 2) (1 - U * t ^ 4) i) =",
        "    (1 - V ^ 2 * t ^ 2) * (1 - U * t ^ 2) * (1 - U * t ^ 4) *",
        "      kernelNumerator t d U V := by",
        "  rw [raw_numerators_sum]",
        "  unfold rawNumeratorSum kernelNumerator",
        "  field_simp",
        "  ring",
        "",
        "theorem fifty_region_sum (t d U V : K) (hd : d ≠ 0)",
        "    (hP : 1 - d * V * t ≠ 0) (hN : 1 - V * t / d ≠ 0)",
        "    (hE : 1 - V ^ 2 * t ^ 2 ≠ 0) (hF : 1 - U * t ^ 2 ≠ 0)",
        "    (hG : 1 - U * t ^ 4 ≠ 0) :",
        "    (∑ i : Fin 50, regionTerms t d U V i) = regionKernel t d U V := by",
        "  let P := 1 - d * V * t",
        "  let N := 1 - V * t / d",
        "  let E := 1 - V ^ 2 * t ^ 2",
        "  let F := 1 - U * t ^ 2",
        "  let G := 1 - U * t ^ 4",
        "  have hh := region_numerators_sum t d U V hd",
        "  have hs : (d ^ 2 * P * N * E * F * G) *",
        "      (∑ i : Fin 50, regionTerms t d U V i) =",
        "      E * F * G * kernelNumerator t d U V := by",
        "    rw [Finset.mul_sum]",
        "    calc",
        "      _ = ∑ i : Fin 50, rawRegionNumerators t d U V P N E F G i := by",
        "        apply Finset.sum_congr rfl",
        "        intro i _",
        "        exact region_term_cleared t d U V P N E F G hd hP hN hE hF hG i",
        "      _ = _ := hh",
        "  have hden : d ^ 2 * P * N * E * F * G ≠ 0 :=",
        "    mul_ne_zero (mul_ne_zero (mul_ne_zero (mul_ne_zero",
        "      (mul_ne_zero (pow_ne_zero 2 hd) hP) hN) hE) hF) hG",
        "  apply (mul_right_inj' hden).mp",
        "  rw [hs]",
        "  change E * F * G * kernelNumerator t d U V =",
        "    (d ^ 2 * P * N * E * F * G) * (kernelNumerator t d U V / (d ^ 2 * P * N))",
        "  have hpn : d ^ 2 * P * N ≠ 0 := mul_ne_zero (mul_ne_zero (pow_ne_zero 2 hd) hP) hN",
        "  have hcancel (x y z : K) (hy : y ≠ 0) : y * z * (x / y) = z * x := by",
        "    field_simp <;> ring",
        "  simpa [mul_assoc] using",
        "    (hcancel (kernelNumerator t d U V) (d ^ 2 * P * N) (E * F * G) hpn).symm",
        "",
        "end Algebra",
        "end FourierJacobi",
        "",
    ]
    (ROOT / "FourierJacobi/Algebra/RegionSum.lean").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
